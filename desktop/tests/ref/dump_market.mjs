// Reference market data from the web build, for the GDScript port tests.
// Run from the repo root (needs Node 22+):  node desktop/tests/ref/dump_market.mjs
// Writes desktop/tests/ref/market_ref.json. Re-run when js/market.js, js/data.js
// or a collection JSON changes, and commit the result.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..', '..');
globalThis.fetch = async url => ({ ok: true, json: async () => JSON.parse(readFileSync(join(root, url), 'utf8')) });

const M = await import(join(root, 'js', 'market.js'));
const { loadCollections } = await import(join(root, 'js', 'data.js'));
const { sets, order } = await loadCollections('');

const DAY0 = 2993000; // a market day in late 2026
const DAYS = 30;
const UUID = '3f2c9a4e-8b1d-4c7a-9e5f-1a2b3c4d5e6f';
const p = x => Number(x.toPrecision(13));


// cyrb53 is private in market.js; rand(parts) = hash(SEED + '|' + parts) / 2^53,
// so rand x 2^53 (an exact integer) pins the hash bit for bit.
const rands = [];
for (const seed of [M.LEGACY_SEED, UUID]) {
  M.setSeed(seed);
  for (const parts of [['base:1', 9, 332555], ['set:jungle', 35, 85514], ['k', 'ev', -3], ['Ünïcode ★', 'up', 7]]) {
    rands.push({ seed, parts, hash: M.hashRand(...parts) * 9007199254740992 });
  }
}

function dump(seed, every) {
  M.setSeed(seed);
  const cards = {};
  for (const id of order) {
    const set = sets[id];
    set.cards.forEach((card, i) => {
      if (i % every) return;
      const m = [];
      for (let d = DAY0; d < DAY0 + DAYS; d++) m.push(p(M.cardMultiplier(set, card, d)));
      cards[`${set.id}:${card.id}`] = m;
    });
  }
  return { seed, every, cards };
}

const values = {};
let total = 0;
for (const id of order) for (const c of sets[id].cards) { values[`${id}:${c.id}`] = p(c.value); total++; }

const news = [];
M.setSeed(M.LEGACY_SEED);
for (const id of order.slice(0, 5)) for (const c of sets[id].cards.slice(0, 20)) {
  for (let d = DAY0; d < DAY0 + DAYS; d++) for (const n of M.newsFor(sets[id], c, d)) news.push([`${id}:${c.id}`, d, n.day, n.kind, n.text]);
}

const out = {
  note: 'Generated by dump_market.mjs from the web build. Do not edit.',
  day0: DAY0, days: DAYS, collections: order.length, cards: total,
  rands, values, news,
  runs: [dump(M.LEGACY_SEED, 1), dump(UUID, 7)],
};
writeFileSync(join(here, 'market_ref.json'), JSON.stringify(out));
console.log(`market_ref.json: ${order.length} collections, ${total} cards, ${news.length} news`);
